"""'AI 냐 사람이냐' 물음 알아보기 — 손님이 상대가 사람인지 · AI · 봇 · 로봇 · 자동응답 · 챗봇 · 매크로인지 묻는 글(코드 규칙).

설계서 17.1 · 17.8 · 원장 R10-27: 손님이 이렇게 물으면 초안 없이 늘 사람에게 넘긴다 — AI 가 사람인 척하면 안 되고, 정직한
답('AI 입니다')도 1단계에서는 사람이 정한다. 15분 바퀴 · 빠른 길 모두 두뇌를 부르기 **전에** 이 함수로 거른다(첫 거름).
놓친 물음은 두뇌 기본 지시문(:mod:`.brain_prompt` 10번)과 보내기 전 검사(:mod:`.checks_rules` '사람이라고 하는 글')가 한 번 더
막는다(둘째 · 셋째 거름 — 검수 R13-5).

- **넓게 잡으면** 초안이 안 뜨고(직원 일이 는다), **좁게 잡으면** AI 가 사람인 척하게 된다 — 둘 다 시험한다
  (``tests/domains/test_cs_realtime.py`` · ``test_cs_realtime_guards.py`` — 검수 R13 목록 53 · 47 포함).
- 규칙은 '누구냐' 말(AI · 인공지능 · 챗봇 · 봇 · 로봇 · 자동응답 · 매크로 · 사람 · 상담원 · 직원 …) **바로 뒤에** 정체를 묻는
  끝말('이세요' · '인가요' · '맞나요' · '아니죠' · '임' · '같아요' …)이나 지금 답하는 일('이 답하는 거' · '랑 얘기하고 싶어요' …)이
  붙을 때만이다. '로봇청소기' · 'AI 로 만든' · '자동응답 메시지 받았어요' 는 사이에 다른 말이 끼어 걸리지 않는다.
- **앞말 보기**: 정체 끝말 · 답하는 일 꼴은 바로 앞 낱말이 사물 · 사람 수를 꾸미는 말이면 물음이 아니다('가구 조립 로봇인가요' ·
  '두 사람이에요' · '그 사람이 답장' · '설치하는 사람이'). 앞 낱말이 없거나, 문장 끝 · 이음말('…요' · '…데' · '…고')이거나,
  '혹시 · 지금 · 진짜 · 이거 · 분' 같은 말일 때만 물음으로 본다.
- 글은 이 함수 안에서만 본다 — 로그 · 예외에 싣지 않는다.
"""

from __future__ import annotations

import re
from typing import Iterable

__all__ = ["ASK_HUMAN_MEMO", "ASK_HUMAN_MEMO_HEAD", "ASKED_IF_AI", "asks_if_human", "any_asks_if_human"]

#: 차례 기록의 넘김 까닭 · 건너뜀 코드(글이 아니다).
ASKED_IF_AI = "asked_if_ai"
#: 넘김 메모의 머리 — 같은 미답 묶음에 이 메모가 이미 있으면 다시 올리지 않는다(검수 R13-9).
ASK_HUMAN_MEMO_HEAD = "[AI 초안 없음]"
#: 메모 스위치일 때 올리는 비공개 한 줄 — 손님에게 보내지 않는다(초안 없음).
ASK_HUMAN_MEMO = f"{ASK_HUMAN_MEMO_HEAD} 손님이 상대가 사람인지 AI 인지 물었습니다 — 직원이 직접 답해 주세요(손님에게 보내지 않는 메모)"

# '누구냐' 말. 영어는 앞뒤가 영문자가 아닐 때만(메일 · rain 같은 낱말 속 'ai' 는 아니다).
_LATIN = r"(?<![a-z])(?:a\.?i\.?|chat\s*gpt|gpt|chat\s*bot|robot|bot)(?![a-z])"
_KOREAN = r"(?:에이아이|인공\s*지능|챗\s*봇|챗\s*(?:지피티|gpt)|지피티|로봇|봇|매크로|자동\s*(?:응답|답변|답장))"
_WHO = rf"(?:{_LATIN}|{_KOREAN})"
_PERSON = r"(?:사람|인간|상담원|상담사|직원)(?:\s*(?:님|분))?"
# 정체를 묻는 끝말 — '누구냐' 말 바로 뒤(빈칸 · 받침 조사 '이 · 가' 만 허용). '인지' 는 '궁금 · 모르' 가 이어질 때만,
# '인건' 은 '인건가요' 만('사람 인건비' · '사람인지라' 는 아니다).
_IDENTITY_END = (
    r"(?:이|가)?\s*(?:이세요|세요|이신가요|신가요|이신지|이에요|에요|이예요|예요|인가요|인가|인건가요|인거죠|인거예요"
    r"|인지\s*(?:궁금|모르|알고|확인|여쭤|물어)|이야|야|이냐|냐|임|이죠|죠|입니까|이십니까|십니까|이요\s*[?？]"
    r"|맞(?:나요|죠|지요|아요|으세요|으신가요|으시죠|으시지요|습니까|냐|니|음)"
    r"|아니(?:에요|죠|지요|세요|신가요|신지|냐|야|시죠)|아닌가요|아닌지|같아요|같은데|같네요|같다|같음|[?？])"
)
# 지금 답하는 일(현재 · 물음 꼴) — '답해줬는데' · '답장을 안 해요' · '대화해 보고' 같은 지난 일 · 손님 일은 아니다.
_ANSWERING_NOW = (
    r"(?:직접\s*)?(?:대답|답변|답장|답|응대|응답|상담|채팅|보)\s*(?:을|를)?\s*(?:하|해)?\s*(?:주)?\s*(?:시|셔)?"
    r"\s*(?:는\s*(?:거|건|걸|게|중)|나요|니|냐|는지|ㄴ가요|고\s*있)"
)
_TALK_WANT = (r"(?:이랑|랑|하고|과|와|한테|에게|께)\s*(?:대화|얘기|이야기|상담|통화|채팅)\s*(?:을|를)?\s*(?:하|해|받)?"
              r"\s*(?:고\s*싶|하고\s*싶|받고\s*싶|는\s*(?:거|건)|중|원해|원합|하게\s*해)")
# 사람 수 · 사물을 꾸미는 앞말이 아니어야 하는 꼴(아래 :func:`_lead_ok` 가 앞 낱말을 본다).
_CONTEXTUAL = tuple(re.compile(pattern, re.IGNORECASE) for pattern in (
    rf"{_WHO}\s*{_IDENTITY_END}",  # 'AI 인가요' · '봇임?' · '로봇 같은데요' · '매크로예요'
    rf"(?<!\d){_PERSON}\s*{_IDENTITY_END}",  # '사람이세요' · '사람 맞으시죠' · '직원분이세요' · '사람이 아니신가요'
    rf"(?<!\d){_PERSON}\s*(?:이|가|께서)\s*{_ANSWERING_NOW}",  # '사람이 답하는 거예요' · '상담사님이 답하시는'
    rf"(?<!\d){_PERSON}\s*{_TALK_WANT}",  # '사람이랑 얘기하고 싶어요' · '사람한테 상담받고 싶어요'
))
# 앞말과 상관없는 꼴.
_ANYWHERE = tuple(re.compile(pattern, re.IGNORECASE) for pattern in (
    rf"(?:{_WHO}|기계)\s*(?:이|가|랑|이랑|와|과|하고|한테|로|으로)?\s*(?:대화|얘기|이야기|상담|대답|답변|답장|답하|답해|답을|답이"
    rf"|응답|응대|채팅|쓴\s*(?:거|건|글)|쓰(?:는|신)\s*(?:거|건)|작성)",  # 'AI 가 답하는' · 'AI가 쓴 거예요' · '봇이랑 대화'
    r"자동\s*으로\s*(?:대답|답변|답장|답하|답해|응답)",  # '자동으로 답장 오는 거예요'
    r"(?:진짜|실제|정말)\s*(?:로\s*)?(?:사람|인간|상담원|상담사|직원)(?:\s*(?:님|분))?\s*"
    r"(?:[?？]|이세요|이신가요|인가요|인지|이에요|이예요|이죠|맞|아니|이랑|하고|과\s*대화|와\s*대화"
    r"|(?:이|가|께서)\s*(?:직접\s*)?(?:대답|답변|답장|답|응대|상담))",  # '진짜사람?' · '실제 상담사님이 답하시는'
    r"(?:상담원|상담사|사람|직원)\s*(?:이랑|과|와|하고|으로|로)?\s*연결",  # '상담원 연결해 주세요'
    r"(?:말고|아니라|대신)\s*(?:진짜\s*)?(?:사람|상담원|상담사|직원)",  # '자동응답 말고 사람이요'
    r"(?:^|[\s,.!?~])누구(?:세요|신가요|신지|예요|에요|야|냐)",  # '누구세요?'
    r"(?<![a-z])are\s+you\s+(?:an?\s+)?(?:bot|robot|human|real|ai|person)(?![a-z])",
))
#: 그대로 물음 앞에 와도 되는 낱말(부사 · 가리킴 · '분').
_LEAD_WORDS = frozenset({
    "혹시", "혹", "지금", "진짜", "정말", "실제", "진짜로", "정말로", "실제로", "그럼", "그러면", "근데", "그런데", "아니면",
    "설마", "그냥", "이거", "이건", "이게", "여기", "저기", "거기", "그쪽", "당신", "너", "님", "분", "답변", "상담", "혹시나",
    "계속", "직접", "솔직히", "답장",
})
#: 사람 수 · 가리킴 앞말 — 이 낱말 뒤 '사람이에요' 는 정체 물음이 아니다('네 사람이에요' 의 '네' 는 문장 끝이 아니다).
_COUNT_WORDS = frozenset({"한", "두", "세", "네", "다섯", "여섯", "일곱", "여덟", "아홉", "열", "몇", "여러", "이", "그", "저",
                          "어떤", "모든"})
#: 문장 끝 · 이음말 끝 글자 — 앞 낱말이 이렇게 끝나면 새 말의 시작으로 본다('기계적인데 사람 맞아요' · '말고 사람이요').
_CLAUSE_ENDS = frozenset("요다까죠데고면서네니냐지")
_HANGUL = re.compile(r"[가-힣]")


def _lead_ok(body: str, start: int) -> bool:
    """찾은 꼴 앞 낱말이 물음의 시작으로 볼 만한가 — 사물 · 사람 수를 꾸미는 말이면 거짓."""
    before = body[:start]
    if before and not before[-1].isspace():  # 붙여 쓴 앞말('혹시AI세요' · '청소로봇이에요')
        token = re.split(r"[\s,.!?~]", before)[-1]
    else:
        stripped = before.rstrip()
        if not stripped or stripped[-1] in ",.!?~)]…":
            return True
        token = stripped.split()[-1]
    if not token or not _HANGUL.search(token):
        return True
    if token in _COUNT_WORDS:
        return False
    return token in _LEAD_WORDS or token[-1] in _CLAUSE_ENDS


def asks_if_human(text: str) -> bool:
    """손님 글이 상대가 사람인지 · AI(봇 · 로봇 · 자동응답 · 챗봇 · 매크로)인지 묻는가. 글자가 아니거나 비면 거짓."""
    if not isinstance(text, str) or not text.strip():
        return False
    body = " ".join(text.split())
    if any(pattern.search(body) for pattern in _ANYWHERE):
        return True
    return any(_lead_ok(body, match.start()) for pattern in _CONTEXTUAL for match in pattern.finditer(body))


def any_asks_if_human(texts: Iterable[str]) -> bool:
    """글 여럿 가운데 하나라도 'AI 냐 사람이냐' 물음인가(마지막 직원 답 뒤 손님 글 묶음에 쓴다)."""
    return any(asks_if_human(text) for text in texts)
